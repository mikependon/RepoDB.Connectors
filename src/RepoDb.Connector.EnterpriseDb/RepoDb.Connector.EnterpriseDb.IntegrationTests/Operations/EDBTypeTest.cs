        #region Id (BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY)

        [TestMethod]
        public void TestEDBTypeForIdColumn()
        {
            using (var connection = new EDBConnection(Database.ConnectionString))
            {
                // Setup
                connection.Open();
                using (var insertCommand = connection.CreateCommand())
                {
                    insertCommand.CommandText = "INSERT INTO \"InsertModel\" (\"RowGuid\") VALUES (gen_random_uuid());";
                    insertCommand.ExecuteNonQuery();
                }

                // Act
                using (var command = connection.CreateCommand())
                {
                    command.CommandText = "SELECT \"Id\" FROM \"InsertModel\" LIMIT 1;";
                    using (var reader = command.ExecuteReader())
                    {
                        reader.Read();

                        // Assert
                        Assert.AreEqual(typeof(long), reader.GetFieldType(0));
                        Assert.IsGreaterThan(0L, reader.GetInt64(0));
                        Assert.IsFalse(reader.IsDBNull(0));
                    }
                }
            }
        }

