        #region Helpers

        private static EDBDataReader InsertAndRead(
            EDBConnection connection,
            string columnName,
            object value)
        {
            using (var insertCommand = connection.CreateCommand())
            {
                insertCommand.CommandText =
                    $"INSERT INTO \"InsertModel\" (\"RowGuid\", \"{columnName}\") VALUES (gen_random_uuid(), @value);";
                insertCommand.Parameters.AddWithValue("@value", value);
                insertCommand.ExecuteNonQuery();
            }

            var selectCommand = connection.CreateCommand();
            selectCommand.CommandText = $"SELECT \"{columnName}\" FROM \"InsertModel\" LIMIT 1;";
            var reader = selectCommand.ExecuteReader();
            reader.Read();
            return reader;
        }

